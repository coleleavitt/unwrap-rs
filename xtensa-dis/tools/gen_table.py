#!/usr/bin/env python3
"""Generate src/table.rs from LLVM's Xtensa TableGen records.

    llvm-tblgen -dump-json -I llvm/include -I llvm/lib/Target/Xtensa \
        llvm/lib/Target/Xtensa/Xtensa.td -o xtensa.json
    python3 tools/gen_table.py xtensa.json > src/table.rs

Records come from llvm-project at llvmorg-22.1.8 (ca7933e), the same
LLVM the decoder is validated against (`llvm-mc --triple=xtensa
-mcpu=esp32`). Every instruction of that ISA is enabled on esp32.
"""
import json, re, sys

KINDS = {
    "AR": "Ar", "FPR": "Fpr", "BR": "Br", "MR": "Mr", "MR01": "Mr01", "MR23": "Mr23",
    "SR": "Sr", "UR": "Ur",
    "mem8": "Mem8", "mem16": "Mem16", "mem32": "Mem32", "mem32n": "Mem32n",
    "brtarget": "Branch", "ltarget": "Loop", "pcrel32call": "Call", "jumptarget": "Jump",
    "L32Rtarget": "L32r", "imm8": "Imm8", "imm8_sh8": "Imm8Sh8", "imm12m": "Imm12",
    "uimm4": "Uimm4", "uimm5": "Uimm5", "imm1_16": "Imm1To16", "imm1n_15": "Imm1nTo15",
    "imm32n_95": "Imm32nTo95", "imm8n_7": "Imm8nTo7", "imm64n_4n": "Imm64nTo4n",
    "entry_imm12": "Entry", "shimm1_31": "Shimm1To31", "b4const": "B4const",
    "b4constu": "B4constu", "imm7_22": "Imm7To22",
}

def hexlit(v):
    return f"0x{v >> 16:04x}_{v & 0xffff:04x}"

def segments(bits):
    """(inst_bit, var_bit) pairs -> [(inst_lo, len, var_lo)] runs."""
    out = []
    for ib, vb in sorted(bits):
        if out and out[-1][0] + out[-1][1] == ib and out[-1][2] + out[-1][1] == vb:
            out[-1][1] += 1
        else:
            out.append([ib, 1, vb])
    return out

def main(path):
    j = json.load(open(path))
    rows = []
    for name in j["!instanceof"]["Instruction"]:
        d = j[name]
        if not isinstance(d, dict) or d.get("Namespace") != "Xtensa" or d.get("isPseudo") \
                or d.get("isCodeGenOnly") or not d.get("Inst") or d.get("Size") not in (2, 3):
            continue
        size = d["Size"]
        mask = match = 0
        fields = {}
        for bit, b in enumerate(d["Inst"][: size * 8]):
            if isinstance(b, int):
                mask |= 1 << bit
                match |= b << bit
            elif isinstance(b, dict) and "var" in b:
                fields.setdefault(b["var"], []).append((bit, b.get("index", 0)))
        kinds = {a[1]: a[0]["def"] for lst in ("OutOperandList", "InOperandList")
                 for a in d[lst]["args"]}
        asm = d["AsmString"]
        mnemonic, _, rest = asm.partition("\t")
        syntax = re.sub(r"\$(\w+)", "{}", rest)
        operands = []
        for var in re.findall(r"\$(\w+)", rest):
            kind = KINDS[kinds[var]]
            operands.append((kind, segments(fields.get(var, []))))
        rows.append((size, bin(mask).count("1"), name, mask, match, mnemonic.strip(), operands, syntax))
    # Most specific encoding first, so a narrower match wins over a wider one.
    rows.sort(key=lambda r: (r[0], -r[1], r[2]))
    print("// @generated by tools/gen_table.py from LLVM's Xtensa TableGen records")
    print("// (llvm-project llvmorg-22.1.8, ca7933e). Do not edit by hand.")
    print("use crate::{Field, Kind, Spec};")
    print()
    for size, label in ((2, "NARROW"), (3, "WIDE")):
        sel = [r for r in rows if r[0] == size]
        print(f"pub const {label}: [Spec; {len(sel)}] = [")
        for _, _, name, mask, match, mn, ops, syntax in sel:
            fs = ", ".join(
                "(Kind::%s, &[%s])" % (k, ", ".join(f"Field({a}, {n}, {v})" for a, n, v in segs))
                for k, segs in ops)
            print(f"    Spec {{ mnemonic: {json.dumps(mn)}, syntax: {json.dumps(syntax)}, mask: {hexlit(mask)}, bits: {hexlit(match)}, operands: &[{fs}] }}, // {name}")
        print("];")

main(sys.argv[1])
